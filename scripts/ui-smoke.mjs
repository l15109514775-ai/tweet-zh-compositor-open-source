import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { at } from '../src/paths.mjs';
const { chromium } = await import('playwright');
const browser = await chromium.launch({ headless: true, downloadsPath: at('test-results', 'ui-downloads') });
const page = await browser.newPage({ viewport: { width: 1500, height: 1060 }, locale: 'zh-CN', acceptDownloads: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = [];
try {
  await page.goto('http://127.0.0.1:4317');
  await page.waitForSelector('[data-path="post.translation"]');
  assert.equal(await page.locator('[data-path="post.author.name"]').inputValue(), '');
  checks.push('新帖昵称、账号、互动数字默认空白，无参考数据继承');
  await page.getByRole('button', { name: '载入测试样例' }).click();
  await page.waitForFunction(() => document.querySelector('[data-path="post.id"]').value === '1000000000000000001');
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/render') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '生成预览', exact: true }).click();
  const exampleResult = await (await responsePromise).json();
  await page.waitForFunction(() => !!document.querySelector('#previewPane img'), { timeout: 60000 });
  await page.locator('#previewPane img').evaluate(img => img.decode());
  assert.equal(await page.locator('#previewPane img').evaluate(img => img.naturalWidth), 2560);
  assert.match(await page.locator('#report').innerText(), /TEST_FIXTURE/);
  checks.push('网页预览产出 2560px PNG，并明确标出测试数据不可发布');
  await page.screenshot({ path: at('test-results', 'ui-desktop.png'), fullPage: false });
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '保存输入 JSON' }).click()]);
  const downloadFile = at('test-results', 'ui-downloads', 'saved-input.json');
  await fs.mkdir(at('test-results', 'ui-downloads'), { recursive: true });
  await download.saveAs(downloadFile);
  assert.equal(JSON.parse(await fs.readFile(downloadFile, 'utf8')).post.id, '1000000000000000001');
  checks.push('保存 JSON 可解析，保留完整输入');
  await page.locator('[data-path="post.translation"]').fill('修改后的中文译文\n日本語と emoji🐉');
  assert.equal(await page.locator('[data-path="post.review.translationConfirmed"]').isChecked(), false);
  assert.equal(await page.locator('#downloads a').count(), 0);
  checks.push('修改译文会取消逐字核对确认，并撤下旧下载链接');
  await page.locator('[data-action="add-quote"]').first().click();
  assert.equal(await page.locator('[data-post="post.quote"]').count(), 1);
  assert.equal(await page.locator('[data-path="post.sourceQuote"]').inputValue(), 'present');
  await page.locator('[data-action="remove-quote"]').first().click();
  assert.equal(await page.locator('[data-path="post.sourceQuote"]').inputValue(), 'unknown');
  checks.push('引用层可添加/移除；移除后需重新核对来源引用状态');
  await page.locator('#uploads').setInputFiles(at('examples', 'assets', 'test-media-4.png'));
  await page.waitForFunction(() => document.querySelector('#assetList').textContent.includes('test-media-4.png'));
  checks.push('素材上传通过原文件接口并可在表单选择');
  await page.getByRole('button', { name: '检查并导出成品' }).click();
  await page.waitForFunction(() => !document.querySelector('#publish').disabled, { timeout: 60000 });
  assert.equal(await page.locator('#previewPane img').count(), 0);
  assert.match(await page.locator('#status').innerText(), /阻止发布/);
  checks.push('未通过核对的输入不会得到成品 PNG');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: at('test-results', 'ui-mobile.png'), fullPage: false });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  checks.push('390px 窄屏网页无横向溢出');
  assert.deepEqual(errors, []);
  const forbidden = await fetch('http://127.0.0.1:4317/api/render', { method: 'POST', headers: { Origin: 'https://example.invalid', 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(forbidden.status, 403);
  checks.push('服务仅监听 loopback，并拒绝跨站写请求');
  const relationInput = await (await fetch('http://127.0.0.1:4317/api/example', { method: 'POST' })).json();
  relationInput.post.quote = structuredClone(relationInput.post);
  relationInput.post.sourceQuote = 'present';
  relationInput.post.relationship = { type: 'repost', authorName: relationInput.post.quote.author.name, url: relationInput.post.quote.url };
  const relationResponse = await fetch('http://127.0.0.1:4317/api/render', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ input: relationInput, mode: 'preview' }) });
  const relationResult = await relationResponse.json();
  assert.equal(relationResponse.status, 200);
  assert.ok(relationResult.report.issues.some(i => i.code === 'RELATIONSHIP_UNKNOWN'));
  assert.equal(relationResult.report.publishable, false);
  assert.ok(relationResult.png);
  checks.push('真实渲染接口遇到转推缺少作者账号时写校验报告并生成警告预览，不抛异常');
  // Hold the response until after a real form edit. This makes the race reproducible.
  // The synthetic ready response tests client invalidation only, not source correctness.
  for (const mode of ['publish', 'preview']) {
    let received;
    let release;
    const requestSeen = new Promise(resolve => { received = resolve; });
    const gate = new Promise(resolve => { release = resolve; });
    const handler = async route => {
      received();
      await gate;
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ...exampleResult, report: { ...exampleResult.report, status: 'ready', publishable: true } }) });
    };
    await page.route('**/api/render', handler);
    const button = mode === 'publish' ? '#publish' : '#preview';
    await page.locator(button).click();
    await requestSeen;
    if (mode === 'publish') await page.locator('[data-path="post.translation"]').fill('请求处理中修改的中文译文');
    else await page.locator('#displayTimezone').selectOption('Asia/Shanghai');
    release();
    await page.waitForFunction(selector => !document.querySelector(selector).disabled, button, { timeout: 60000 });
    await page.unroute('**/api/render', handler);
    assert.equal(await page.locator('#downloads a').count(), 0);
    assert.equal(await page.locator('#previewPane img').count(), 0);
    assert.match(await page.locator('#status').innerText(), /旧结果已丢弃/);
    checks.push(mode === 'publish' ? '导出处理中修改译文，旧成品响应不恢复下载链接' : '预览处理中修改时区，旧预览响应被丢弃');
  }
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
  await fs.writeFile(at('test-results', 'ui-smoke.json'), JSON.stringify({ checks, pageErrors: errors }, null, 2) + '\n');
}
console.log(JSON.stringify({ passed: checks.length, checks }));
